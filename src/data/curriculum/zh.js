/* ============================== 展开成词条 ==============================
 * 词条 id 由内容决定（不靠数组下标），所以往表里插数据不会让已有词条换 id
 * —— 已存进掌握度里的 id 不会因为加字而指向别的东西。 */

function hanziEntries(rows, grade) {
  return rows.map(([text, pinyin, word]) => ({
    id: `zh-hanzi-${text}`, lang: LANG, kind: 'hanzi', grade,
    text, pinyin, word, spellKey: pinyin,
  }));
}
function wordEntries(rows, grade) {
  return rows.map(([pinyin, text]) => ({
    id: `zh-word-${text}`, lang: LANG, kind: 'word', grade,
    text, pinyin, spellKey: pinyin,
  }));
}
